#1. Find Maximum and Minimum

import numpy as np

arr = np.array([10, 25, 5, 40, 15])

print("Array:", arr)
print("Maximum:", arr.max())
print("Minimum:", arr.min())


#2. Sum of Array

import numpy as np

arr = np.array([10, 20, 30, 40, 50])

print("Array:", arr)
print("Sum:", arr.sum())


#3. Calculate Mean and Median

import numpy as np

arr = np.array([10, 20, 30, 40, 50])

print("Mean:", np.mean(arr))
print("Median:", np.median(arr))

#4. Multiply Every Element

import numpy as np

arr = np.array([1, 2, 3, 4, 5])

result = arr * 2

print("Original:", arr)
print("After multiplication:", result)


#5. Add Two Arrays

import numpy as np

a = np.array([10, 20, 30])
