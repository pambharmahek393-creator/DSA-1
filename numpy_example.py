#1. array()

import numpy as np

arr = np.array([10, 20, 30, 40, 50])

print("Array:", arr)


#2. arange()

import numpy as np

arr = np.arange(1, 11, 2)

print("Array:", arr)


#3. linspace()

import numpy as np

arr = np.linspace(0, 10, 5)

print("Array:", arr)


#4. logspace()

import numpy as np

arr = np.logspace(1, 3, 5)

print("Array:", arr)


